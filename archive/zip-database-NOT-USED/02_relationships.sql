-- HR – VERIFIER (MANAGES) [1:N]
ALTER TABLE VERIFIER
ADD CONSTRAINT FK_VERIFIER_HR FOREIGN KEY (HR_ID)
REFERENCES HR (HR_ID) ON DELETE CASCADE;

-- Multivalued Child Tables Foreign Keys
ALTER TABLE VERIFIER_EMAIL
ADD CONSTRAINT FK_VEMAIL_VERIFIER FOREIGN KEY (VERIFIER_ID)
REFERENCES VERIFIER (VERIFIER_ID) ON DELETE CASCADE;

ALTER TABLE VERIFIER_PHONE
ADD CONSTRAINT FK_VPHONE_VERIFIER FOREIGN KEY (VERIFIER_ID)
REFERENCES VERIFIER (VERIFIER_ID) ON DELETE CASCADE;

ALTER TABLE APPLICANT_EMAIL
ADD CONSTRAINT FK_AEMAIL_APPLICANT FOREIGN KEY (APPLICANT_ID)
REFERENCES APPLICANT (APPLICANT_ID) ON DELETE CASCADE;

ALTER TABLE APPLICANT_PHONE
ADD CONSTRAINT FK_APHONE_APPLICANT FOREIGN KEY (APPLICANT_ID)
REFERENCES APPLICANT (APPLICANT_ID) ON DELETE CASCADE;

-- APPLICANT – CERTIFICATE (RECEIVES) [1:N]
ALTER TABLE CERTIFICATE
ADD CONSTRAINT FK_CERT_APPLICANT FOREIGN KEY (APPLICANT_ID)
REFERENCES APPLICANT (APPLICANT_ID) ON DELETE CASCADE;

-- ISSUER – CERTIFICATE (ISSUES) [1:N]
ALTER TABLE CERTIFICATE
ADD CONSTRAINT FK_CERT_ISSUER FOREIGN KEY (ISSUER_ID)
REFERENCES ISSUER (ISSUER_ID) ON DELETE RESTRICT;

-- CERTIFICATE_TYPE – CERTIFICATE (HAS_TYPE) [1:N]
ALTER TABLE CERTIFICATE
ADD CONSTRAINT FK_CERT_TYPE FOREIGN KEY (TYPE_ID)
REFERENCES CERTIFICATE_TYPE (TYPE_ID) ON DELETE RESTRICT;

-- CERTIFICATE – REVOCATION (HAS_REVOCATION) [1:1]
ALTER TABLE REVOCATION
ADD CONSTRAINT FK_REVOCATION_CERT FOREIGN KEY (CERTIFICATE_ID)
REFERENCES CERTIFICATE (CERTIFICATE_ID) ON DELETE CASCADE;

-- CERTIFICATE – VERIFICATION (HAS) [1:N]
ALTER TABLE VERIFICATION
ADD CONSTRAINT FK_VERIF_CERT FOREIGN KEY (CERTIFICATE_ID)
REFERENCES CERTIFICATE (CERTIFICATE_ID) ON DELETE CASCADE;

-- VERIFIER – VERIFICATION (PERFORMS) [1:N] (Nullable for public verifications)
ALTER TABLE VERIFICATION
ADD CONSTRAINT FK_VERIF_VERIFIER FOREIGN KEY (VERIFIER_ID)
REFERENCES VERIFIER (VERIFIER_ID) ON DELETE SET NULL;

