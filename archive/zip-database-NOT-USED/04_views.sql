-- View 1: HR and Verifier Compensation Details (Derived Salary)
CREATE OR REPLACE VIEW VW_HR_COMPENSATION AS
SELECT 
    H.HR_ID,
    H.BASIC,
    H.DA,
    H.HRA,
    H.SALARY AS TOTAL_SALARY,
    H.LEAVE_BALANCE,
    COUNT(V.VERIFIER_ID) AS TOTAL_VERIFIERS_MANAGED
FROM HR H
LEFT JOIN VERIFIER V ON H.HR_ID = V.HR_ID
GROUP BY H.HR_ID, H.BASIC, H.DA, H.HRA, H.SALARY, H.LEAVE_BALANCE;

-- View 2: Complete Certificate Verification Master View (Calculates Derived Status)
CREATE OR REPLACE VIEW VW_CERTIFICATE_VERIFY AS
SELECT 
    C.CERTIFICATE_ID,
    C.CERTIFICATE_NO,
    C.TITLE,
    C.ISSUE_DATE,
    C.EXPIRY_DATE,
    C.DOCUMENT_URL,
    C.CERTIFICATE_HASH,
    C.DIGITAL_SIGNATURE,
    C.QR_CODE,
    -- Derived Dynamic Status: Revocation takes precedence, followed by expiration, else valid
    CASE 
        WHEN R.REVOCATION_ID IS NOT NULL THEN 'REVOKED'
        WHEN C.EXPIRY_DATE IS NOT NULL AND C.EXPIRY_DATE < TRUNC(SYSDATE) THEN 'EXPIRED'
        ELSE 'VALID'
    END AS DERIVED_STATUS,
    
    -- Revocation attributes (if applicable)
    R.REVOCATION_ID,
    R.REASON AS REVOCATION_REASON,
    R.REVOKED_DATE,
    
    -- Applicant Composite Attributes
    A.APPLICANT_ID,
    A.FIRST_NAME || ' ' || NVL2(A.MIDDLE_NAME, A.MIDDLE_NAME || ' ', '') || A.LAST_NAME AS APPLICANT_NAME,
    'XXXX-XXXX-' || SUBSTR(A.AADHAR_CARD, 9, 4) AS APPLICANT_MASKED_AADHAR,
    A.STREET || ', ' || A.CITY || ', ' || A.STATE || ' - ' || A.PINCODE AS APPLICANT_FULL_ADDRESS,
    
    -- Issuer Attributes
    I.ISSUER_ID,
    I.ISSUER_NAME,
    I.ORGANISATION AS ISSUER_ORGANISATION,
    I.EMAIL AS ISSUER_EMAIL,
    I.PHONE AS ISSUER_PHONE,
    I.PUBLIC_KEY AS ISSUER_PUBLIC_KEY,
    
    -- Certificate Type Attributes
    T.TYPE_ID,
    T.TYPE_NAME,
    T.DESCRIPTION AS TYPE_DESCRIPTION
FROM CERTIFICATE C
JOIN APPLICANT A ON C.APPLICANT_ID = A.APPLICANT_ID
JOIN ISSUER I ON C.ISSUER_ID = I.ISSUER_ID
JOIN CERTIFICATE_TYPE T ON C.TYPE_ID = T.TYPE_ID
LEFT JOIN REVOCATION R ON C.CERTIFICATE_ID = R.CERTIFICATE_ID;

-- View 3: Dashboard Analytics Aggregation View
CREATE OR REPLACE VIEW VW_SYSTEM_ANALYTICS AS
SELECT
    (SELECT COUNT(*) FROM CERTIFICATE) AS TOTAL_CERTIFICATES,
    (SELECT COUNT(*) FROM VW_CERTIFICATE_VERIFY WHERE DERIVED_STATUS = 'VALID') AS ACTIVE_CERTIFICATES,
    (SELECT COUNT(*) FROM VW_CERTIFICATE_VERIFY WHERE DERIVED_STATUS = 'EXPIRED') AS EXPIRED_CERTIFICATES,
    (SELECT COUNT(*) FROM VW_CERTIFICATE_VERIFY WHERE DERIVED_STATUS = 'REVOKED') AS REVOKED_CERTIFICATES,
    (SELECT COUNT(*) FROM VERIFICATION) AS TOTAL_VERIFICATIONS,
    (SELECT COUNT(*) FROM APPLICANT) AS TOTAL_APPLICANTS,
    (SELECT COUNT(*) FROM ISSUER) AS TOTAL_ISSUERS,
    (SELECT COUNT(*) FROM VERIFIER) AS TOTAL_VERIFIERS
FROM DUAL;

