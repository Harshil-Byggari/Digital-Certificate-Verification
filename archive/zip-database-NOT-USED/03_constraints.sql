-- Fast lookup indexes for verification searches
CREATE INDEX IDX_CERT_NO ON CERTIFICATE (CERTIFICATE_NO);
CREATE INDEX IDX_CERT_HASH ON CERTIFICATE (CERTIFICATE_HASH);
CREATE INDEX IDX_CERT_APPLICANT ON CERTIFICATE (APPLICANT_ID);
CREATE INDEX IDX_CERT_ISSUER ON CERTIFICATE (ISSUER_ID);
CREATE INDEX IDX_CERT_STATUS ON CERTIFICATE (STATUS);

CREATE INDEX IDX_VERIF_CERT ON VERIFICATION (CERTIFICATE_ID);
CREATE INDEX IDX_VERIF_TIME ON VERIFICATION (VERIFICATION_TIME);
CREATE INDEX IDX_REVOC_CERT ON REVOCATION (CERTIFICATE_ID);

-- Email and phone uniqueness per entity
CREATE UNIQUE INDEX UQ_APP_PRIMARY_EMAIL ON APPLICANT_EMAIL (APPLICANT_ID, CASE WHEN IS_PRIMARY = 'Y' THEN 'Y' END);
CREATE UNIQUE INDEX UQ_APP_PRIMARY_PHONE ON APPLICANT_PHONE (APPLICANT_ID, CASE WHEN IS_PRIMARY = 'Y' THEN 'Y' END);
CREATE UNIQUE INDEX UQ_VER_PRIMARY_EMAIL ON VERIFIER_EMAIL (VERIFIER_ID, CASE WHEN IS_PRIMARY = 'Y' THEN 'Y' END);
CREATE UNIQUE INDEX UQ_VER_PRIMARY_PHONE ON VERIFIER_PHONE (VERIFIER_ID, CASE WHEN IS_PRIMARY = 'Y' THEN 'Y' END);

-- Date validation constraint
ALTER TABLE CERTIFICATE
ADD CONSTRAINT CHK_CERT_EXPIRY CHECK (EXPIRY_DATE IS NULL OR EXPIRY_DATE > ISSUE_DATE);

