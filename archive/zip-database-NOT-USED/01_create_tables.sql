-- Clean up existing tables if present
BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
    'VERIFICATION', 'REVOCATION', 'CERTIFICATE', 'APPLICANT_EMAIL', 
    'APPLICANT_PHONE', 'VERIFIER_EMAIL', 'VERIFIER_PHONE', 'APPLICANT', 
    'CERTIFICATE_TYPE', 'ISSUER', 'VERIFIER', 'HR', 'AUTH_USER'
  )) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
  END LOOP;
END;
/

-- 1. HR Table
CREATE TABLE HR (
    HR_ID         VARCHAR2(36)   NOT NULL,
    BASIC         NUMBER(10,2)   NOT NULL,
    DA            NUMBER(10,2)   NOT NULL,
    HRA           NUMBER(10,2)   NOT NULL,
    SALARY        NUMBER(10,2)   GENERATED ALWAYS AS (BASIC + DA + HRA) VIRTUAL,
    LEAVE_BALANCE NUMBER(3)      DEFAULT 24 NOT NULL,
    CREATED_AT    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_HR PRIMARY KEY (HR_ID),
    CONSTRAINT CHK_HR_BASIC CHECK (BASIC >= 0),
    CONSTRAINT CHK_HR_DA CHECK (DA >= 0),
    CONSTRAINT CHK_HR_HRA CHECK (HRA >= 0),
    CONSTRAINT CHK_HR_LEAVE CHECK (LEAVE_BALANCE >= 0)
);

-- 2. VERIFIER Table
CREATE TABLE VERIFIER (
    VERIFIER_ID   VARCHAR2(36)   NOT NULL,
    HR_ID         VARCHAR2(36)   NOT NULL,
    FIRST_NAME    VARCHAR2(50)   NOT NULL,
    MIDDLE_NAME   VARCHAR2(50),
    LAST_NAME     VARCHAR2(50)   NOT NULL,
    AADHAR_CARD   VARCHAR2(12)   NOT NULL,
    DOJ           DATE           NOT NULL,
    ROLE          VARCHAR2(50)   NOT NULL,
    VERIFIER_TYPE VARCHAR2(50)   NOT NULL,
    ORGANISATION  VARCHAR2(150)  NOT NULL,
    ADDRESS       VARCHAR2(250)  NOT NULL,
    CREATED_AT    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_VERIFIER PRIMARY KEY (VERIFIER_ID),
    CONSTRAINT UQ_VERIFIER_AADHAR UNIQUE (AADHAR_CARD),
    CONSTRAINT CHK_VERIFIER_AADHAR CHECK (LENGTH(AADHAR_CARD) = 12),
    CONSTRAINT CHK_VERIFIER_TYPE CHECK (VERIFIER_TYPE IN ('INTERNAL', 'EXTERNAL', 'GOVERNMENT', 'ENTERPRISE'))
);

-- 3. Multivalued: VERIFIER_EMAIL
CREATE TABLE VERIFIER_EMAIL (
    EMAIL_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    VERIFIER_ID   VARCHAR2(36)   NOT NULL,
    EMAIL         VARCHAR2(120)  NOT NULL,
    IS_PRIMARY    CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT CHK_VEMAIL_PRI CHECK (IS_PRIMARY IN ('Y', 'N'))
);

-- 4. Multivalued: VERIFIER_PHONE
CREATE TABLE VERIFIER_PHONE (
    PHONE_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    VERIFIER_ID   VARCHAR2(36)   NOT NULL,
    PHONE_NUMBER  VARCHAR2(15)   NOT NULL,
    IS_PRIMARY    CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT CHK_VPHONE_PRI CHECK (IS_PRIMARY IN ('Y', 'N'))
);

-- 5. APPLICANT Table (Composite Name and Composite Address)
CREATE TABLE APPLICANT (
    APPLICANT_ID  VARCHAR2(36)   NOT NULL,
    FIRST_NAME    VARCHAR2(50)   NOT NULL,
    MIDDLE_NAME   VARCHAR2(50),
    LAST_NAME     VARCHAR2(50)   NOT NULL,
    DOB           DATE           NOT NULL,
    AADHAR_CARD   VARCHAR2(12)   NOT NULL,
    STREET        VARCHAR2(150)  NOT NULL,
    CITY          VARCHAR2(60)   NOT NULL,
    STATE         VARCHAR2(60)   NOT NULL,
    PINCODE       VARCHAR2(10)   NOT NULL,
    CREATED_AT    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_APPLICANT PRIMARY KEY (APPLICANT_ID),
    CONSTRAINT UQ_APPLICANT_AADHAR UNIQUE (AADHAR_CARD),
    CONSTRAINT CHK_APPLICANT_AADHAR CHECK (LENGTH(AADHAR_CARD) = 12)
);

-- 6. Multivalued: APPLICANT_EMAIL
CREATE TABLE APPLICANT_EMAIL (
    EMAIL_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    APPLICANT_ID  VARCHAR2(36)   NOT NULL,
    EMAIL         VARCHAR2(120)  NOT NULL,
    IS_PRIMARY    CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT CHK_AEMAIL_PRI CHECK (IS_PRIMARY IN ('Y', 'N'))
);

-- 7. Multivalued: APPLICANT_PHONE
CREATE TABLE APPLICANT_PHONE (
    PHONE_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    APPLICANT_ID  VARCHAR2(36)   NOT NULL,
    PHONE_NUMBER  VARCHAR2(15)   NOT NULL,
    IS_PRIMARY    CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT CHK_APHONE_PRI CHECK (IS_PRIMARY IN ('Y', 'N'))
);

-- 8. CERTIFICATE_TYPE Table
CREATE TABLE CERTIFICATE_TYPE (
    TYPE_ID       VARCHAR2(36)   NOT NULL,
    TYPE_NAME     VARCHAR2(100)  NOT NULL,
    DESCRIPTION   VARCHAR2(500),
    CREATED_AT    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_CERT_TYPE PRIMARY KEY (TYPE_ID),
    CONSTRAINT UQ_CERT_TYPE_NAME UNIQUE (TYPE_NAME)
);

-- 9. ISSUER Table
CREATE TABLE ISSUER (
    ISSUER_ID     VARCHAR2(36)   NOT NULL,
    ISSUER_NAME   VARCHAR2(150)  NOT NULL,
    ORGANISATION  VARCHAR2(150)  NOT NULL,
    PUBLIC_KEY    CLOB           NOT NULL,
    PHONE         VARCHAR2(20)   NOT NULL,
    EMAIL         VARCHAR2(120)  NOT NULL,
    STREET        VARCHAR2(150)  NOT NULL,
    CITY          VARCHAR2(60)   NOT NULL,
    STATE         VARCHAR2(60)   NOT NULL,
    PINCODE       VARCHAR2(10)   NOT NULL,
    CREATED_AT    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_ISSUER PRIMARY KEY (ISSUER_ID)
);

-- 10. CERTIFICATE Table
CREATE TABLE CERTIFICATE (
    CERTIFICATE_ID      VARCHAR2(36)   NOT NULL,
    CERTIFICATE_NO      VARCHAR2(50)   NOT NULL,
    TITLE               VARCHAR2(200)  NOT NULL,
    APPLICANT_ID        VARCHAR2(36)   NOT NULL,
    ISSUER_ID           VARCHAR2(36)   NOT NULL,
    TYPE_ID             VARCHAR2(36)   NOT NULL,
    ISSUE_DATE          DATE           NOT NULL,
    EXPIRY_DATE         DATE,
    DOCUMENT_URL        VARCHAR2(500)  NOT NULL,
    QR_CODE             CLOB           NOT NULL,
    CERTIFICATE_HASH    VARCHAR2(64)   NOT NULL,
    DIGITAL_SIGNATURE   CLOB           NOT NULL,
    STATUS              VARCHAR2(20)   DEFAULT 'VALID' NOT NULL,
    CREATED_AT          TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_CERTIFICATE PRIMARY KEY (CERTIFICATE_ID),
    CONSTRAINT UQ_CERTIFICATE_NO UNIQUE (CERTIFICATE_NO),
    CONSTRAINT CHK_CERT_STATUS CHECK (STATUS IN ('VALID', 'EXPIRED', 'REVOKED'))
);

-- 11. REVOCATION Table (1:1 with CERTIFICATE)
CREATE TABLE REVOCATION (
    REVOCATION_ID   VARCHAR2(36)   NOT NULL,
    CERTIFICATE_ID  VARCHAR2(36)   NOT NULL,
    REASON          VARCHAR2(500)  NOT NULL,
    REVOKED_DATE    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_REVOCATION PRIMARY KEY (REVOCATION_ID),
    CONSTRAINT UQ_REVOCATION_CERT UNIQUE (CERTIFICATE_ID)
);

-- 12. VERIFICATION Table (1:N audit ledger)
CREATE TABLE VERIFICATION (
    VERIFICATION_ID   VARCHAR2(36)   NOT NULL,
    CERTIFICATE_ID    VARCHAR2(36)   NOT NULL,
    VERIFIER_ID       VARCHAR2(36),
    VERIFICATION_TIME TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    USER_AGENT        VARCHAR2(300),
    IP_ADDRESS        VARCHAR2(50)   NOT NULL,
    RESULT            VARCHAR2(20)   NOT NULL,
    METHOD            VARCHAR2(50)   NOT NULL,
    REMARKS           VARCHAR2(500),
    CONSTRAINT PK_VERIFICATION PRIMARY KEY (VERIFICATION_ID),
    CONSTRAINT CHK_VERIF_RESULT CHECK (RESULT IN ('VALID', 'EXPIRED', 'REVOKED', 'INVALID')),
    CONSTRAINT CHK_VERIF_METHOD CHECK (METHOD IN ('QR_SCAN', 'MANUAL_ENTRY', 'API_INTEGRATION', 'BATCH_VERIFY'))
);

-- 13. AUTH_USER Table
CREATE TABLE AUTH_USER (
    USER_ID       VARCHAR2(36)   NOT NULL,
    USERNAME      VARCHAR2(100)  NOT NULL,
    PASSWORD_HASH VARCHAR2(256)  NOT NULL,
    ROLE          VARCHAR2(30)   NOT NULL,
    ENTITY_ID     VARCHAR2(36)   NOT NULL,
    IS_ACTIVE     CHAR(1)        DEFAULT 'Y' NOT NULL,
    LAST_LOGIN    TIMESTAMP,
    CREATED_AT    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_AUTH_USER PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_AUTH_USERNAME UNIQUE (USERNAME),
    CONSTRAINT CHK_AUTH_ROLE CHECK (ROLE IN ('APPLICANT', 'VERIFIER', 'HR', 'ADMIN')),
    CONSTRAINT CHK_AUTH_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
);

