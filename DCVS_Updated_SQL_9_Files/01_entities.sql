-- 01_entities.sql : all main entities (columns + checks + primary/unique keys). FKs come in 02.

CREATE TABLE app_config (
  cfg_key    VARCHAR2(50)  PRIMARY KEY,
  cfg_value  VARCHAR2(500) NOT NULL
);

CREATE TABLE certificate_type (
  type_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  type_name    VARCHAR2(100) NOT NULL,
  description  VARCHAR2(500),
  CONSTRAINT uq_type_name UNIQUE (type_name)
);

CREATE TABLE applicant (
  applicant_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  first_name    VARCHAR2(50)  NOT NULL,      -- composite attribute NAME
  middle_name   VARCHAR2(50),
  last_name     VARCHAR2(50)  NOT NULL,
  dob           DATE          NOT NULL,
  aadhar_card   VARCHAR2(12)  NOT NULL,
  street        VARCHAR2(150),               -- composite attribute ADDRESS
  city          VARCHAR2(80),
  state         VARCHAR2(80),
  pincode       VARCHAR2(6),
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_applicant_aadhar UNIQUE (aadhar_card),
  CONSTRAINT ck_applicant_aadhar CHECK (REGEXP_LIKE(aadhar_card,'^[0-9]{12}$')),
  CONSTRAINT ck_applicant_pin    CHECK (pincode IS NULL OR REGEXP_LIKE(pincode,'^[0-9]{6}$')),
  CONSTRAINT ck_applicant_dob    CHECK (dob <= DATE '2100-01-01')
);

CREATE TABLE issuer (
  issuer_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  issuer_name   VARCHAR2(150) NOT NULL,
  public_key    VARCHAR2(500),               -- generated by PKG_ISSUER (key fingerprint)
  organisation  VARCHAR2(200),
  email         VARCHAR2(150),
  phone         VARCHAR2(20),
  street        VARCHAR2(150),
  city          VARCHAR2(80),
  state         VARCHAR2(80),
  pincode       VARCHAR2(6),
  CONSTRAINT ck_issuer_pin CHECK (pincode IS NULL OR REGEXP_LIKE(pincode,'^[0-9]{6}$'))
);

-- Secret signing key lives in its own table. NEVER expose this table through ORDS.
CREATE TABLE issuer_secret (
  issuer_id   NUMBER PRIMARY KEY,
  secret_key  VARCHAR2(128) NOT NULL
);

CREATE TABLE hr (
  hr_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  hr_name    VARCHAR2(100),                  -- convenience label for UI (not in ER diagram)
  basic      NUMBER(12,2) NOT NULL,
  da         NUMBER(12,2) DEFAULT 0 NOT NULL,
  hra        NUMBER(12,2) DEFAULT 0 NOT NULL,
  leave_days NUMBER(4)    DEFAULT 0 NOT NULL,   -- "Leave" in ER diagram
  salary     NUMBER GENERATED ALWAYS AS (basic + da + hra) VIRTUAL,  -- DERIVED attribute
  CONSTRAINT ck_hr_amounts CHECK (basic >= 0 AND da >= 0 AND hra >= 0 AND leave_days >= 0)
);

CREATE TABLE verifier (
  verifier_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  first_name     VARCHAR2(50) NOT NULL,
  middle_name    VARCHAR2(50),
  last_name      VARCHAR2(50) NOT NULL,
  aadhar_card    VARCHAR2(12) NOT NULL,
  doj            DATE NOT NULL,
  verifier_role  VARCHAR2(80),               -- "Role" in ER diagram
  organization   VARCHAR2(200),
  verifier_type  VARCHAR2(50),
  street         VARCHAR2(150),
  city           VARCHAR2(80),
  state          VARCHAR2(80),
  pincode        VARCHAR2(6),
  hr_id          NUMBER,                     -- HR MANAGES VERIFIER (FK in 02)
  CONSTRAINT uq_verifier_aadhar UNIQUE (aadhar_card),
  CONSTRAINT ck_verifier_aadhar CHECK (REGEXP_LIKE(aadhar_card,'^[0-9]{12}$')),
  CONSTRAINT ck_verifier_pin    CHECK (pincode IS NULL OR REGEXP_LIKE(pincode,'^[0-9]{6}$'))
);

CREATE SEQUENCE seq_cert_no START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE certificate (
  certificate_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  certificate_no     VARCHAR2(30)  NOT NULL,
  title              VARCHAR2(200) NOT NULL,
  applicant_id       NUMBER NOT NULL,        -- RECEIVES   (total participation)
  type_id            NUMBER NOT NULL,        -- HAS_TYPE
  issuer_id          NUMBER NOT NULL,        -- ISSUES     (total participation)
  issue_date         DATE,
  expiry_date        DATE,
  document_url       VARCHAR2(500),
  upload_certificate VARCHAR2(500),          -- attribute of RECEIVES
  qr_code            VARCHAR2(600),          -- verification URL encoded in the QR
  digital_signature  VARCHAR2(200),
  certificate_hash   VARCHAR2(64),           -- computed at issue, recomputed at verification
  is_issued          CHAR(1) DEFAULT 'N' NOT NULL,
  created_at         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_certificate_no UNIQUE (certificate_no),
  CONSTRAINT ck_cert_issued CHECK (is_issued IN ('Y','N')),
  CONSTRAINT ck_cert_dates  CHECK (expiry_date IS NULL OR issue_date IS NULL OR expiry_date >= issue_date)
);

CREATE TABLE revocation (
  revocation_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  certificate_id NUMBER NOT NULL,            -- HAS_REVOCATION (1:1, total participation)
  reason         VARCHAR2(500) NOT NULL,
  revoked_date   DATE DEFAULT SYSDATE NOT NULL,
  revoked_by     NUMBER,
  CONSTRAINT uq_revocation_cert UNIQUE (certificate_id)
);

CREATE TABLE verification (
  verification_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  certificate_id    NUMBER,                  -- NULL when the reference does not exist
  reference_text    VARCHAR2(100),           -- what was typed/scanned
  verifier_id       NUMBER,                  -- NULL for public (anonymous) verification
  verification_time TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  user_agent        VARCHAR2(500),
  ip_address        VARCHAR2(64),
  result            VARCHAR2(20) NOT NULL,
  method            VARCHAR2(20) NOT NULL,
  remarks           VARCHAR2(500),
  CONSTRAINT ck_ver_result CHECK (result IN ('VALID','INVALID','EXPIRED','REVOKED','TAMPERED')),
  CONSTRAINT ck_ver_method CHECK (method IN ('MANUAL','QR','API'))
);

-- HOME PAGE / LOGIN entity
CREATE TABLE account (
  account_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  username      VARCHAR2(100) NOT NULL,      -- "User_ID" on the HOME PAGE entity
  password_hash VARCHAR2(200) NOT NULL,      -- salt:sha256 (never plain text)
  user_type     VARCHAR2(20)  NOT NULL,
  applicant_id  NUMBER,
  verifier_id   NUMBER,
  hr_id         NUMBER,
  status        VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  last_login    TIMESTAMP,
  CONSTRAINT uq_account_username  UNIQUE (username),
  CONSTRAINT uq_account_applicant UNIQUE (applicant_id),   -- LOGIN is 1:1
  CONSTRAINT uq_account_verifier  UNIQUE (verifier_id),
  CONSTRAINT uq_account_hr        UNIQUE (hr_id),
  CONSTRAINT ck_account_status CHECK (status IN ('ACTIVE','DISABLED')),
  CONSTRAINT ck_account_type CHECK (
       (user_type='ADMIN'     AND applicant_id IS NULL     AND verifier_id IS NULL     AND hr_id IS NULL)
    OR (user_type='APPLICANT' AND applicant_id IS NOT NULL AND verifier_id IS NULL     AND hr_id IS NULL)
    OR (user_type='VERIFIER'  AND verifier_id  IS NOT NULL AND applicant_id IS NULL    AND hr_id IS NULL)
    OR (user_type='HR'        AND hr_id        IS NOT NULL AND applicant_id IS NULL    AND verifier_id IS NULL))
);

CREATE TABLE auth_session (
  token_hash  VARCHAR2(64) PRIMARY KEY,
  account_id  NUMBER NOT NULL,
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  expires_at  TIMESTAMP NOT NULL
);
